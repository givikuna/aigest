package aigest.output

import aigest.Version
import aigest.ingest.Ingestor.BinaryFile
import aigest.ingest.Ingestor.FileEntry
import aigest.ingest.Ingestor.IngestBundle
import aigest.ingest.Ingestor.TextFile

import groovy.transform.CompileStatic

@CompileStatic
final class Formatter {

    private Formatter() { }

    static final class DirNode {

        final Map<String, DirNode> dirs
        final List<String> files

        DirNode(Map<String, DirNode> dirs, List<String> files) {
            this.dirs = Collections.unmodifiableMap(new TreeMap<String, DirNode>(dirs))

            List<String> sortedFiles = new ArrayList<String>(files)
            Collections.sort(sortedFiles)

            this.files = Collections.unmodifiableList(sortedFiles)
        }

        static DirNode fromEntries(List<FileEntry> entries) {
            List<List<String>> segmentPaths = entries
                .collect { FileEntry e -> Arrays.asList(e.relativePath.split('/')) }
                .findAll { List<String> segs -> !segs.isEmpty() && !segs.get(0).isEmpty() }

            fromSegmentLists(segmentPaths)
        }

        private static DirNode fromSegmentLists(List<List<String>> paths) {
            List<String> leafFiles = new ArrayList<String>()
            Map<String, List<List<String>>> groupedDirs = new LinkedHashMap<String, List<List<String>>>()

            for (List<String> path : paths) {
                if (path.size() == 1) {
                    leafFiles.add(path.get(0))
                } else {
                    String head = path.get(0)
                    List<List<String>> bucket = groupedDirs.get(head)

                    if (bucket == null) {
                        bucket = new ArrayList<List<String>>()
                        groupedDirs.put(head, bucket)
                    }

                    bucket.add(path.subList(1, path.size()))
                }
            }

            Map<String, DirNode> children = new TreeMap<String, DirNode>()
            groupedDirs.each { String dirName, List<List<String>> subPaths ->
                children.put(dirName, fromSegmentLists(subPaths))
            }

            new DirNode(children, leafFiles)
        }

    }

    static String format(IngestBundle bundle) {
        List<String> sections = new ArrayList<String>()

        sections.add(
            "This file is a merged representation of the entire codebase, combined into a single document by ${Version.NAME}.".toString()
        )

        sections.add(renderFileSummary(bundle))
        sections.add(renderDirectoryStructure(bundle.entries))
        sections.add(renderFiles(bundle.entries))

        String logsSection = bundle.gitLogs.<String>fold(
            { '' },
            { String ignored -> '' },
            { String logs -> renderGitLogs(logs) }
        )

        if (!logsSection.isEmpty()) {
            sections.add(logsSection)
        }

        sections.join('\n\n') + '\n'
    }

    static String renderDirectoryStructure(List<FileEntry> entries) {
        DirNode root = DirNode.fromEntries(entries)
        StringBuilder sb = new StringBuilder()
        sb.append('<directory_structure>\n')
        renderTree(root, 0, sb)
        sb.append('</directory_structure>')
        sb.toString()
    }

    private static void renderTree(DirNode node, int depth, StringBuilder out) {
        String indent = '  '.repeat(depth)

        node.dirs.each { String name, DirNode child ->
            out.append(indent).append(name).append('/\n')
            renderTree(child, depth + 1, out)
        }

        for (String file : node.files) {
            out.append(indent).append(file).append('\n')
        }
    }

    private static String renderFileSummary(IngestBundle bundle) {
        boolean hasLogs = bundle.gitLogs.isAvailable()
        String logsLine = hasLogs ? '\n5. Git commit logs' : ''

        """<file_summary>
This section contains a summary of this file.

<purpose>
This file contains a packed representation of the repository's contents.
It is designed to be easily consumable by AI systems for analysis, code review,
or other automated processes.
</purpose>

<file_format>
The content is organized as follows:
1. This summary section
2. Directory structure
3. Repository files, each consisting of:
  - File path as an attribute
  - Full contents of the file${logsLine}
</file_format>

<usage_guidelines>
- This file should be treated as read-only. Any changes should be made to the
  original repository files, not this packed version.
- When processing this file, use the file path to distinguish
  between different files in the repository.
- Be aware that this file may contain sensitive information. Handle it with
  the same level of security as you would the original repository.
</usage_guidelines>

<notes>
- Generated by ${Version.banner()} using profile '${bundle.activeProfile}'
- Files included: ${bundle.stats.textFiles} text, ${bundle.stats.binaryFiles} binary (${bundle.stats.totalFiles} total)
- Some files may have been excluded based on .gitignore and aigest.json rules
- Binary files are omitted from the <files> section; refer to <directory_structure> for the complete path list
</notes>

</file_summary>"""
    }

    private static String renderFiles(List<FileEntry> entries) {
        StringBuilder sb = new StringBuilder()
        sb.append('<files>\n')
        sb.append("This section contains the contents of the repository's files.\n")

        for (FileEntry entry : entries) {
            entry.fold(
                { BinaryFile ignored -> null },
                { TextFile text ->
                    sb.append('\n<file path="')
                        .append(escapeXmlAttr(text.relativePath))
                        .append('">\n')
                        .append(text.content)
                    if (!text.content.isEmpty() && !text.content.endsWith('\n')) {
                        sb.append('\n')
                    }
                    sb.append('</file>\n')
                    null
                }
            )
        }

        sb.append('</files>')
        sb.toString()
    }

    private static String renderGitLogs(String logs) {
        "<git_logs>\n${logs}\n</git_logs>"
    }

    private static String escapeXmlAttr(String raw) {
        raw.replace('&', '&amp;')
            .replace('"', '&quot;')
            .replace('<', '&lt;')
            .replace('>', '&gt;')
    }

}
